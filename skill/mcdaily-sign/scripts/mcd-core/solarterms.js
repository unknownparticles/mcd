// 返回 {term: '霜降', termLine: '秋将尽，宜吃点好的', festival, festivalLine}
export function resolveDate(dateStr) {
  const d = (dateStr ?? "").slice(0, 10); // yyyy-MM-dd
  const out = { term: null, termLine: "", festival: null, festivalLine: "" };
  let current = null;
  for (const [date, name, line] of TERMS_2026) {
    if (d >= date) current = [name, line];
  }
  if (current) [out.term, out.termLine] = current;
  const md = d.slice(5);
  if (FESTIVALS[md]) {
    [out.festival, out.festivalLine] = FESTIVALS[md];
  }
  return out;
}
